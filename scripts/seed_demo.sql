-- Working hours: salons Mon-Sat 10:00-19:00, barbers Mon-Sun 11:00-21:00 -------
INSERT INTO working_hours (id, master_id, location_id, weekday, start_time, end_time)
SELECT
    ('55555555-5555-4555-8555-0000000' || n || '000' || d)::uuid,
    ('11111111-1111-4111-8111-00000000000' || n)::uuid,
    ('33333333-3333-4333-8333-00000000000' || n)::uuid,
    d,
    CASE WHEN n IN (5, 6) THEN '11:00'::time ELSE '10:00'::time END,
    CASE WHEN n IN (5, 6) THEN '21:00'::time ELSE '19:00'::time END
FROM generate_series(1, 8) AS n
CROSS JOIN generate_series(1, 7) AS d
WHERE d <= CASE WHEN n IN (5, 6) THEN 7 ELSE 6 END
ON CONFLICT (id) DO NOTHING;

